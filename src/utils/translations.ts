/**
 * Universal translation getter that looks up the key in the current language,
 * with fallback to Hindi, then English, then raw key.
 */
export const getTranslation = (key: string, lang: Language): string => {
  const dict = UI_TRANSLATIONS[key];
  if (!dict) return key;

  return dict[lang] || dict['hi'] || dict['en'] || key;
};

/**
 * Translation helper for general text
 */
export const t = (key: string, lang: Language): string => {
  return getTranslation(key, lang);
};
